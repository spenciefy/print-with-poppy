import Database from "better-sqlite3";
import fs from "node:fs";
import { config } from "./config.js";
import { installDatabase } from "./storage-runtime.js";
import { initializeStore } from "./store-schema.js";
fs.mkdirSync(`${config.dataDir}/photos`, { recursive: true, mode: 0o700 });
const database = new Database(`${config.dataDir}/poppy.sqlite`);
database.pragma("journal_mode = WAL");
database.pragma("foreign_keys = ON");
database.pragma("busy_timeout = 5000");
initializeStore(database);
installDatabase(database);
export * from "./store-core.js";
